const root = resolve(import.meta.dirname, "..");
const assets: Record<string, { svg: string; png: string; monochrome: boolean }> = {};
for (const [kind, names] of [
  ["files", files],
  ["tools", tools],
] as const) {
  for (const [name, filename] of Object.entries(names)) {
    const path =
      kind === "files"
        ? resolve(root, "scripts/vendor/vscode-icons", `${filename}.svg`)
        : resolve(root, "node_modules/@vscode/codicons/src/icons", `${filename}.svg`);
    const svg = (await readFile(path, "utf8")).trim();
    const png = await sharp(Buffer.from(svg.replaceAll("currentColor", "#ffffff")))
      .resize(64, 64)
      .png()
      .toBuffer();
    assets[name] = {
      svg,
      png: `data:image/png;base64,${png.toString("base64")}`,
      monochrome: kind === "tools",
    };
  }
}
await mkdir(resolve(root, "client/generated"), { recursive: true });
await writeFile(
  resolve(root, "client/generated/icons.ts"),
  `// Generated by npm run build:assets. vscode-icons 13.0.0 / Codicons 0.0.46-24. See docs/third-party-notices.md.\nexport const iconAssets = ${JSON.stringify(assets)} as const;\n`,
);
// Keep the large renderer in the server bundle. Fetch it only for a Mermaid preview.
const runtime = await readFile(resolve(root, "node_modules/mermaid/dist/mermaid.min.js"));
await mkdir(resolve(root, "server/generated"), { recursive: true });
await writeFile(
  resolve(root, "server/generated/mermaid.ts"),
  `// Generated from Mermaid 12.3.0 (MIT). See docs/third-party-notices.md.\nexport const mermaidRuntime = ${JSON.stringify({ version: "12.3.0", gzip: gzipSync(runtime, { level: 9 }).toString("base64") })} as const;\n`,
);
console.log(`Built ${Object.keys(assets).length} icons and offline Mermaid runtime.`);
