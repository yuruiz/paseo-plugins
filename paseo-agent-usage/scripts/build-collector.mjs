import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outJs = join(root, "server", "remote", "collector.bundle.js");

await build({
  entryPoints: [join(root, "server", "remote", "collector.ts")],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node14",
  outfile: outJs,
  logLevel: "warning",
});

const bundle = await readFile(outJs, "utf8");
const escaped = bundle.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const ts = `// Generated by scripts/build-collector.mjs - do not edit by hand.\nexport const COLLECTOR_SCRIPT = \`${escaped}\`;\n`;
await writeFile(join(root, "server", "remote", "collector.script.ts"), ts);
console.log(`collector.bundle.js: ${bundle.length} bytes`);
console.log(`collector.script.ts: ${ts.length} bytes`);
